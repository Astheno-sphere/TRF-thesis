"""
Concordance / dependency-map generator for the length cut. Builds the thesis's dependency
graph so a trim in one chapter cannot silently break another (TRIM_RATIONALE.md §9).

Scans the chapter + front-matter files and writes DEPENDENCY_MAP.md:
  (1) INBOUND CROSS-REFERENCES — for each target (a Section/Chapter/Table/Figure/Proposition/
      Corollary/Appendix), which files point at it. Cutting the content behind a target with
      inbound pointers is the domino risk; the map names every pointer that would dangle.
  (2) DEFINED-TERM LOCATIONS — each frozen term, where it lives and its home (first chapter).
  (3) RECURRING CLAIMS — each repeated claim phrase, its home (first occurrence) and its
      restatement sites (the only cuttable copies).

Usage:
  python3 handoff_tools/concordance.py            # write DEPENDENCY_MAP.md
  python3 handoff_tools/concordance.py --check     # global resolver: every cross-ref in every
                                                   # file resolves to a heading/label that exists
"""
import re, sys, pathlib, collections

FILES = ["Front_Matter_v1.md","Chapter1_Introduction_v2.md","Chapter2_LitReview_v2_FINAL.md",
 "Chapter3_Methodology_v1.md","Chapter4_TRF_Model_v1.md","Chapter5_Demonstration_v1.md",
 "Chapter6_Discussion_v1.md","Chapter7_Conclusion_v1.md","Appendix_B_Search_Log.md",
 "Appendix_C_Evaluation_Instrument.md"]

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import trim_inspector as T

# Section/Table/Figure numbers are N.N exactly — the negative lookahead (?!\.?\d) rejects
# external multi-dot numbering such as IHE ITI-55 "Section 3.55.4.1.2.1".
REF = re.compile(r"(?:Section|§)\s?(\d+\.\d+)(?!\.?\d)|Chapter\s+(\d+)|Table\s+(\d+\.\d+)(?!\.?\d)|"
                 r"Figure\s+(\d+\.\d+)(?!\.?\d)|Proposition\s+(\d+)|Corollary\s+(\d+\.\d+)(?!\.?\d)|Appendix\s+([A-C])")

def load():
    d = {}
    for f in FILES:
        p = pathlib.Path(f)
        if p.exists(): d[f] = p.read_text(encoding="utf-8")
    return d

def targets_present(texts):
    """What section/table/figure/prop/cor/appendix labels actually exist (can be pointed at)."""
    present = set()
    for f, s in texts.items():
        for m in re.findall(r"^#{1,4}\s+(?:Chapter\s+)?(\d+)\.\s", s, flags=re.M): present.add(("Chapter", m))
        for m in re.findall(r"^#{1,4}\s+(\d+\.\d+)", s, flags=re.M): present.add(("Section", m))
        for m in re.findall(r"\*?Table\s+(\d+\.\d+)", s): present.add(("Table", m))
        for m in re.findall(r"Figure\s+(\d+\.\d+)", s): present.add(("Figure", m))
        for m in re.findall(r">\s*\*?Proposition\s+(\d+)", s): present.add(("Proposition", m))
        for m in re.findall(r"Proposition\s+(\d+)", s): present.add(("Proposition", m))
        for m in re.findall(r"Corollary\s+(\d+\.\d+)", s): present.add(("Corollary", m))
        for m in re.findall(r"Appendix\s+([A-C])", s): present.add(("Appendix", m))
    return present

def inbound(texts):
    idx = collections.defaultdict(list)
    for f, s in texts.items():
        for m in REF.finditer(T.body(s)):
            sec, ch, tb, fg, pr, co, ap = m.groups()
            key = (("Section",sec) if sec else ("Chapter",ch) if ch else ("Table",tb) if tb
                   else ("Figure",fg) if fg else ("Proposition",pr) if pr else
                   ("Corollary",co) if co else ("Appendix",ap))
            idx[key].append(f)
    return idx

def check(texts):
    present = targets_present(texts); inb = inbound(texts); bad = []
    for key, srcs in inb.items():
        kind, num = key
        if kind in ("Section","Table","Figure","Proposition","Corollary","Appendix","Chapter") and key not in present:
            # Chapter/Proposition numeric may appear only as refs; only flag Section/Table/Figure/Corollary/Appendix
            if kind in ("Section","Table","Figure","Corollary","Appendix"):
                bad.append((key, sorted(set(srcs))))
    if bad:
        print("DANGLING CROSS-REFERENCES (target content absent):")
        for key, srcs in bad: print(f"  {key[0]} {key[1]}  <- referenced by {', '.join(srcs)}")
        return False
    print(f"GLOBAL XREF CHECK: all {sum(len(v) for v in inb.values())} cross-references resolve.")
    return True

def recurring(texts):
    out = {}
    order = [f for f in FILES if f in texts]
    for ph in T.RECURRING:
        sites = [f for f in order if ph in T.body(texts[f]).lower()]
        if len(sites) > 1: out[ph] = sites
    return out

def defined(texts):
    order = [f for f in FILES if f in texts]
    out = {}
    for d in T.DEFINED:
        sites = [(f, T.body(texts[f]).count(d)) for f in order if d in T.body(texts[f])]
        if sites: out[d] = sites
    return out

def write_map(texts):
    inb = inbound(texts); rec = recurring(texts); dfn = defined(texts)
    L = ["# DEPENDENCY MAP — auto-generated by handoff_tools/concordance.py",
         "", "Do not hand-edit; regenerate. Read before cutting any section (TRIM_RATIONALE.md §9).",
         "A target with inbound pointers is domino-risk: cutting the content behind it strands every pointer listed.", ""]
    L.append("## 1. Inbound cross-references (who depends on each target)")
    for key in sorted(inb, key=lambda k:(k[0],k[1])):
        srcs = collections.Counter(inb[key])
        L.append(f"- **{key[0]} {key[1]}** <- " + ", ".join(f"{f.split('_')[0]}×{n}" for f,n in srcs.items()))
    L.append("\n## 2. Recurring claims (home = first; restatements are the only cuttable copies)")
    for ph, sites in rec.items():
        L.append(f"- \"{ph}\" — HOME **{sites[0].split('_')[0]}**; restatements: " +
                 ", ".join(s.split('_')[0] for s in sites[1:]))
    L.append("\n## 3. Defined-term locations (home chapter holds the definition; never cut there)")
    for d, sites in dfn.items():
        L.append(f"- `{d}` — " + ", ".join(f"{f.split('_')[0]}×{n}" for f,n in sites))
    pathlib.Path("DEPENDENCY_MAP.md").write_text("\n".join(L)+"\n", encoding="utf-8")
    print(f"wrote DEPENDENCY_MAP.md: {len(inb)} targets, {len(rec)} recurring claims, {len(dfn)} defined terms")

if __name__ == "__main__":
    texts = load()
    if "--check" in sys.argv:
        sys.exit(0 if check(texts) else 1)
    write_map(texts)

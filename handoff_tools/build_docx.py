def reorder(parent, order):
    kids = list(parent)
    def key(k):
        n = k.tag.split("}")[1] if "}" in k.tag else k.tag
        return order.index(n) if n in order else len(order)
    for k in kids: parent.remove(k)
    for k in sorted(kids, key=key): parent.append(k)


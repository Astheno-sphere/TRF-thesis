def run(text, bold=False, italic=False, size=None, color=None, font=None, style=None):
    r = el("r"); rp = sub(r, "rPr")
    if style: sub(rp, "rStyle", val=style)
    if font: sub(rp, "rFonts", ascii=font, hAnsi=font, cs=font)
    if bold: sub(rp, "b")
    if italic: sub(rp, "i")
    if color: sub(rp, "color", val=color)
    if size: sub(rp, "sz", val=size); sub(rp, "szCs", val=size)
    t = sub(r, "t"); t.text = text; t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    return r

def para(style=None, jc=None, before=None, after=None, keep=False, pagebreak=False, tabs=None, ind=None):
    p = el("p"); pp = sub(p, "pPr")
    if style: sub(pp, "pStyle", val=style)
    if keep: sub(pp, "keepNext")
    if pagebreak: sub(pp, "pageBreakBefore")
    if tabs:
        ts = sub(pp, "tabs")
        for pos, leader in tabs: sub(ts, "tab", val="right", leader=leader, pos=pos)
    if before is not None or after is not None:
        sub(pp, "spacing", before=before or 0, after=after or 0)
    if ind: sub(pp, "ind", **ind)
    if jc: sub(pp, "jc", val=jc)
    return p

def fld(p, instr, placeholder="#"):
    for kind in ("begin",):
        r = sub(p, "r"); sub(r, "fldChar", fldCharType=kind)
    r = sub(p, "r"); t = sub(r, "instrText"); t.text = " %s " % instr
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    r = sub(p, "r"); sub(r, "fldChar", fldCharType="separate")
    p.append(run(placeholder))
    r = sub(p, "r"); sub(r, "fldChar", fldCharType="end")




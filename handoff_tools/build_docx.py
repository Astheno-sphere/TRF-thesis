def captions(body):
    found = []
    for p in body.iter(q("p")):
        if pstyle(p) != "TableCaption":
            continue
        txt = ptext(p)
        m = re.match(r"Table ([A-Z0-9]+)\.(\d+[a-z]?)\.", txt)
        if not m:
            continue
        name = "tbl_%s_%s" % (m.group(1), m.group(2))
        # bold the label: split the first run at the end of "Table X.Y."
        lab = m.group(0)
        r0 = p.find("w:r", NS); t0 = r0.find("w:t", NS)
        if t0 is not None and t0.text and t0.text.startswith(lab):
            rest = t0.text[len(lab):]
            t0.text = rest
            lr = copy.deepcopy(r0); lr.find("w:t", NS).text = lab
            rp = rpr_of(lr); rp.insert(0, el("b"))
            for o in rp.findall("w:i", NS): rp.remove(o)
            rpr_of(lr).append(el("color", val=NAVY))
            r0.addprevious(lr)
        bookmark(p, name)
        found.append((name, txt))
    return found


def headings(body):
    toc = []
    for p in body.iter(q("p")):
        st = pstyle(p)
        if st not in ("Heading1", "Heading2"):
            continue
        txt = ptext(p).strip()
        lvl = 1 if st == "Heading1" else 2
        m1 = re.match(r"Chapter (\d+)\.", txt)
        m2 = re.match(r"(\d+)\.(\d+) ", txt)
        ma = re.match(r"Appendix ([A-C])\.", txt)
        if lvl == 1:
            name = "ch_%s" % m1.group(1) if m1 else ("app_%s" % ma.group(1) if ma else "h_" + re.sub(r"\W+", "_", txt)[:30])
        else:
            if not m2:
                continue           # appendix sub-headings and front-matter sub-headings: not in contents
            name = "sec_%s_%s" % m2.groups()
        bookmark(p, name)
        toc.append((lvl, txt, name))
    return toc


LINK = re.compile(r"(Tables? [A-Z0-9]+\.\d+[a-z]?)|(Sections? \d+\.\d+)|(§ ?\d+\.\d+)|(Chapter \d)(?![\d.])")

def link_targets(text, known):
    out = []
    for m in LINK.finditer(text):
        s = m.group(0)
        n = re.search(r"([A-Z0-9]+)\.(\d+[a-z]?)", s) if not m.group(4) else None
        if m.group(1):
            name = "tbl_%s_%s" % n.groups()
        elif m.group(4):
            name = "ch_%s" % s.split()[-1]
        else:
            name = "sec_%s_%s" % n.groups()
        before = text[max(0, m.start() - 20):m.start()]
        if m.group(1) and re.search(r"(TEHDAS2, 2026, |D7\.4, |TEHDAS2 D7\.4, )$", before):
            continue                       # the Joint Action's own tables, not ours
        if name in known:
            out.append((m.start(), m.end(), name))
    return out


def crosslinks(body, known):
    n = 0
    for p in list(body.iter(q("p"))):
        if pstyle(p) in ("Heading1", "Heading2", "Heading3", "TableCaption", "SourceCode", "TOC1", "TOC2"):
            continue
        for r in list(p.findall("w:r", NS)):       # direct runs only (not inside hyperlinks or fields)
            t = r.find("w:t", NS)
            if t is None or not t.text or len(r.findall("w:t", NS)) != 1:
                continue
            tg = link_targets(t.text, known)
            if not tg:
                continue
            text, pos, pieces = t.text, 0, []
            for a, b, name in tg:
                if a > pos: pieces.append((text[pos:a], None))
                pieces.append((text[a:b], name)); pos = b
            if pos < len(text): pieces.append((text[pos:], None))
            for seg, name in pieces:
                nr = copy.deepcopy(r); nt = nr.find("w:t", NS); nt.text = seg
                nt.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
                if name:
                    rp = rpr_of(nr); rp.insert(0, el("rStyle", val="Hyperlink"))
                    h = el("hyperlink", anchor=name, history=1); h.append(nr)
                    r.addprevious(h); n += 1
                else:
                    r.addprevious(nr)
            p.remove(r)
    return n



# ---------------------------------------------------------------- markdown preprocessing
def preprocess(md):
    lines = md.split("\n")
    # drop the assembler's plain title block (everything before "# Front Matter")
    start = next(i for i, l in enumerate(lines) if l.strip() == "# Front Matter")
    lines = lines[start + 1:]
    out, skip = [], False
    for l in lines:
        s = l.strip()
        if s in ("\\pagebreak", "---"):
            continue
        if s == "## Title Page" or s == "## Table of Contents":
            skip = True
            if s == "## Table of Contents":
                out.append("\n```{=openxml}\n<!--CONTENTS-->\n```\n")
            continue
        if skip:
            if s.startswith("## ") or s.startswith("# "):
                skip = False
            else:
                continue
        m = re.match(r"^## (.+)$", l)
        if m and m.group(1) in FRONT:
            out.append("# " + m.group(1) + " {.unnumbered}")
            continue
        m = re.match(r"^\*(Table [A-Z0-9]+\.\d+[a-z]?\. .+)\*$", s)
        if m:
            out += ["", "::: {custom-style=\"Table Caption\"}", m.group(1), ":::", ""]
            continue
        out.append(l)
    return "\n".join(out)


# ---------------------------------------------------------------- XML helpers
def el(tag, **attrs):
    e = etree.Element(q(tag))
    for k, v in attrs.items():
        e.set(q(k), str(v))
    return e

def sub(parent, tag, **attrs):
    e = el(tag, **attrs); parent.append(e); return e

MT = "{http://schemas.openxmlformats.org/officeDocument/2006/math}t"
def ptext(p):
    return "".join(t.text or "" for t in p.iter(q("t"), MT))

def pstyle(p):
    s = p.find("w:pPr/w:pStyle", NS)
    return s.get(q("val")) if s is not None else ""

def ensure(parent, tag, first=False):
    e = parent.find("w:" + tag, NS)
    if e is None:
        e = el(tag)
        parent.insert(0, e) if first else parent.append(e)
    return e

def rpr_of(r):
    return ensure(r, "rPr", first=True)


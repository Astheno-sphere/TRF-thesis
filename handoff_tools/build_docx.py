def captions(body):
    found = []
    for p in body.iter(q("p")):
        if pstyle(p) != "TableCaption":
            continue
        txt = ptext(p)
        m = re.match(r"Table ([A-Z0-9]+)\.(\d+[a-z]?)\.", txt)
        if not m:
            continue
        name = "tbl_%s_%s" % (m.group(1), m.group(2))
        # bold the label: split the first run at the end of "Table X.Y."
        lab = m.group(0)
        r0 = p.find("w:r", NS); t0 = r0.find("w:t", NS)
        if t0 is not None and t0.text and t0.text.startswith(lab):
            rest = t0.text[len(lab):]
            t0.text = rest
            lr = copy.deepcopy(r0); lr.find("w:t", NS).text = lab
            rp = rpr_of(lr); rp.insert(0, el("b"))
            for o in rp.findall("w:i", NS): rp.remove(o)
            rpr_of(lr).append(el("color", val=NAVY))
            r0.addprevious(lr)
        bookmark(p, name)
        found.append((name, txt))
    return found



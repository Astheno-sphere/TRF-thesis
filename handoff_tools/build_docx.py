def main():
    md = preprocess(SRC.read_text(encoding="utf-8"))
    fm = (ROOT / "Front_Matter_v1.md").read_text(encoding="utf-8")
    with tempfile.TemporaryDirectory() as td:
        mdp, raw = os.path.join(td, "in.md"), os.path.join(td, "raw.docx")
        open(mdp, "w", encoding="utf-8").write(md)
        subprocess.run(["pandoc", mdp, "-f", "markdown+raw_attribute", "-o", raw, "--reference-doc", str(REF)],
                       check=True, cwd=ROOT)
        zin = zipfile.ZipFile(raw)
        files = {n: zin.read(n) for n in zin.namelist()}
    doc = etree.fromstring(files["word/document.xml"])
    body = doc.find("w:body", NS)

    style_tables(body)
    space_after_tables(body)
    tables = captions(body)
    toc = headings(body)
    known = {n for n, _ in tables} | {n for _, _, n in toc}
    nlinks = crosslinks(body, known)
    bibliography(body)

    # first heading ("Abstract") must not add a blank page after the title page: title page ends with a break
    marker = None
    for p in body.iter(q("p")):
        if "<!--CONTENTS-->" in etree.tostring(p, encoding="unicode") or ptext(p).strip() == "<!--CONTENTS-->":
            marker = p; break
    # raw openxml comment becomes nothing; find the paragraph after Nomenclature section instead
    first = body[0]
    for e in title_page(fm):
        first.addprevious(e)
    cont = contents_block(toc, tables)
    # place contents before the first chapter heading
    ch1 = next(p for p in body.iter(q("p")) if pstyle(p) == "Heading1" and ptext(p).startswith("Chapter 1"))
    for e in cont:
        ch1.addprevious(e)

    # footer, title page without number
    sect = body.find("w:sectPr", NS)
    if sect is None:
        sect = sub(body, "sectPr")
    rels = etree.fromstring(files["word/_rels/document.xml.rels"])
    rid = "rIdFtr1"
    rel = etree.SubElement(rels, "{http://schemas.openxmlformats.org/package/2006/relationships}Relationship")
    rel.set("Id", rid); rel.set("Type", R.replace("relationships", "relationships/footer")); rel.set("Target", "footer1.xml")
    for o in sect.findall("w:footerReference", NS): sect.remove(o)
    fr = el("footerReference"); fr.set(q("type"), "default"); fr.set("{%s}id" % R, rid); sect.insert(0, fr)
    for o in sect.findall("w:titlePg", NS): sect.remove(o)
    tpg = el("titlePg")
    pgsz = sect.find("w:pgSz", NS)
    # A4, 2.5 cm margins
    for tag in ("pgSz", "pgMar"):
        for o in sect.findall("w:" + tag, NS): sect.remove(o)
    sect.append(el("pgSz", w=11906, h=16838))
    sect.append(el("pgMar", top=1418, right=1418, bottom=1418, left=1418, header=709, footer=709, gutter=0))
    sect.append(tpg)
    files["word/_rels/document.xml.rels"] = etree.tostring(rels, xml_declaration=True, encoding="UTF-8", standalone=True)
    files["word/footer1.xml"] = footer_xml().encode()
    ct = files["[Content_Types].xml"].decode()
    if "footer1.xml" not in ct:
        ct = ct.replace("</Types>", '<Override PartName="/word/footer1.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.footer+xml"/></Types>')
    files["[Content_Types].xml"] = ct.encode()

    files["word/styles.xml"] = fix_styles(files["word/styles.xml"])
    if "word/numbering.xml" in files:                  # pandoc writes short nsid values; schema wants 8 hex digits
        files["word/numbering.xml"] = re.sub(rb'(w:nsid w:val=")([0-9A-Fa-f]{1,7})"',
                                             lambda m: m.group(1) + m.group(2).zfill(8) + b'"', files["word/numbering.xml"])
    sroot = etree.fromstring(files["word/settings.xml"])
    if sroot.find("w:updateFields", NS) is None:
        sroot.append(el("updateFields", val="true"))
    reorder(sroot, SETTINGS_ORDER)
    st = etree.tostring(sroot, xml_declaration=True, encoding="UTF-8", standalone=True).decode()
    if False:
        m = re.search(r"<w:(hdrShapeDefaults|footnotePr|endnotePr|compat|docVars|rsids|mathPr|attachedSchema|themeFontLang|clrSchemeMapping|doNotIncludeSubdocsInStats|doNotAutoCompressPictures|forceUpgrade|captions|readModeInkLockDown|smartTagType|schemaLibrary|shapeDefaults|doNotEmbedSmartTags|decimalSymbol|listSeparator)\b", st)
        st = st[:m.start()] + '<w:updateFields w:val="true"/>' + st[m.start():] if m else st.replace("</w:settings>", '<w:updateFields w:val="true"/></w:settings>')
    files["word/settings.xml"] = st.encode()
    for ppr in doc.iter(q("pPr")):
        reorder(ppr, PPR_ORDER)
    M = "http://schemas.openxmlformats.org/officeDocument/2006/math"
    for e in doc.iter("{%s}dPr" % M):
        reorder(e, ["begChr", "sepChr", "endChr", "grow", "shp", "ctrlPr"])
    for e in doc.iter("{%s}rPr" % M):
        reorder(e, ["lit", "nor", "scr", "sty", "brk", "aln"])
        if e.find("{%s}nor" % M) is not None:          # nor excludes scr/sty (schema choice)
            for o in e.findall("{%s}sty" % M) + e.findall("{%s}scr" % M): e.remove(o)
    files["word/document.xml"] = etree.tostring(doc, xml_declaration=True, encoding="UTF-8", standalone=True)

    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for n, b in files.items():
            z.writestr(n, b)
    print(f"{OUT.name}: {len(tables)} captioned tables, {len(toc)} contents entries, {nlinks} cross-reference links")


if __name__ == "__main__":
    main()

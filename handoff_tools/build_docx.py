# ---------------------------------------------------------------- markdown preprocessing
def preprocess(md):
    lines = md.split("\n")
    # drop the assembler's plain title block (everything before "# Front Matter")
    start = next(i for i, l in enumerate(lines) if l.strip() == "# Front Matter")
    lines = lines[start + 1:]
    out, skip = [], False
    for l in lines:
        s = l.strip()
        if s in ("\\pagebreak", "---"):
            continue
        if s == "## Title Page" or s == "## Table of Contents":
            skip = True
            if s == "## Table of Contents":
                out.append("\n```{=openxml}\n<!--CONTENTS-->\n```\n")
            continue
        if skip:
            if s.startswith("## ") or s.startswith("# "):
                skip = False
            else:
                continue
        m = re.match(r"^## (.+)$", l)
        if m and m.group(1) in FRONT:
            out.append("# " + m.group(1) + " {.unnumbered}")
            continue
        m = re.match(r"^\*(Table [A-Z0-9]+\.\d+[a-z]?\. .+)\*$", s)
        if m:
            out += ["", "::: {custom-style=\"Table Caption\"}", m.group(1), ":::", ""]
            continue
        out.append(l)
    return "\n".join(out)


# ---------------------------------------------------------------- XML helpers
def el(tag, **attrs):
    e = etree.Element(q(tag))
    for k, v in attrs.items():
        e.set(q(k), str(v))
    return e

def sub(parent, tag, **attrs):
    e = el(tag, **attrs); parent.append(e); return e

def ptext(p):
    return "".join(t.text or "" for t in p.iter(q("t")))

def pstyle(p):
    s = p.find("w:pPr/w:pStyle", NS)
    return s.get(q("val")) if s is not None else ""

def ensure(parent, tag, first=False):
    e = parent.find("w:" + tag, NS)
    if e is None:
        e = el(tag)
        parent.insert(0, e) if first else parent.append(e)
    return e

def rpr_of(r):
    return ensure(r, "rPr", first=True)

_bm = [1000]
def bookmark(p, name):
    _bm[0] += 1
    s = el("bookmarkStart", id=_bm[0], name=name); e = el("bookmarkEnd", id=_bm[0])
    ppr = p.find("w:pPr", NS)
    idx = 1 if ppr is not None else 0
    p.insert(idx, s); p.append(e)

def run(text, bold=False, italic=False, size=None, color=None, font=None, style=None):
    r = el("r"); rp = sub(r, "rPr")
    if style: sub(rp, "rStyle", val=style)
    if font: sub(rp, "rFonts", ascii=font, hAnsi=font, cs=font)
    if bold: sub(rp, "b")
    if italic: sub(rp, "i")
    if color: sub(rp, "color", val=color)
    if size: sub(rp, "sz", val=size); sub(rp, "szCs", val=size)
    t = sub(r, "t"); t.text = text; t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    return r

def para(style=None, jc=None, before=None, after=None, keep=False, pagebreak=False, tabs=None, ind=None):
    p = el("p"); pp = sub(p, "pPr")
    if style: sub(pp, "pStyle", val=style)
    if keep: sub(pp, "keepNext")
    if pagebreak: sub(pp, "pageBreakBefore")
    if tabs:
        ts = sub(pp, "tabs")
        for pos, leader in tabs: sub(ts, "tab", val="right", leader=leader, pos=pos)
    if before is not None or after is not None:
        sub(pp, "spacing", before=before or 0, after=after or 0)
    if ind: sub(pp, "ind", **ind)
    if jc: sub(pp, "jc", val=jc)
    return p

def fld(p, instr, placeholder="#"):
    for kind in ("begin",):
        r = sub(p, "r"); sub(r, "fldChar", fldCharType=kind)
    r = sub(p, "r"); t = sub(r, "instrText"); t.text = " %s " % instr
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    r = sub(p, "r"); sub(r, "fldChar", fldCharType="separate")
    p.append(run(placeholder))
    r = sub(p, "r"); sub(r, "fldChar", fldCharType="end")



